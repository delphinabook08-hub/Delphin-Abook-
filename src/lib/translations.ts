export function getTranslations(langCode: string): Translations {
  if (!langCode) return fr;
  const match = translationsMap[langCode] || translationsMap[langCode.toLowerCase()];
  if (match) return match;

  // Partial match checks
  const lower = langCode.toLowerCase();
  if (lower.includes("chines") || lower.includes("中文") || lower.includes("zh")) return zh;
  if (lower.includes("ukrai") || lower.includes("україн") || lower.includes("uk")) return uk;
  if (lower.includes("russ") || lower.includes("рус") || lower.includes("ru")) return ru;
  if (lower.includes("germ") || lower.includes("deutsch") || lower.includes("de")) return de;
  if (lower.includes("arab") || lower.includes("عرب") || lower.includes("ar")) return ar;
  if (lower.includes("french") || lower.includes("français") || lower.includes("fr")) return fr;
  if (lower.includes("english") || lower.includes("anglais") || lower.includes("en")) return en;
  if (lower.includes("lingala")) return ln;
  if (lower.includes("swahili") || lower.includes("kiswahili")) return sw;
  if (lower.includes("portug")) return pt;
  if (lower.includes("spanish") || lower.includes("español")) return es;

  // Fallback to French
  return fr;
}
